#!/usr/bin/env python3
"""Write src/tables.rs: the LALR(1) tables Lark builds for the sequence grammar of the Python GDS.

The Rust parser runs these tables with a lexer that follows Lark's contextual lexer, so that
it accepts and rejects the same files as `fprime-seqgen`, at the same line and column.

    PYTHONHASHSEED=0 python tools/gen_tables.py > src/tables.rs

Needs the Python GDS (`fprime_gds`) and its `lark` installed. Run again only when
`fprime_gds/common/parsers/grammar.lark` changes.
"""
import lark
from fprime_gds.common.parsers.lark_seq_parser import LarkSeqFileParser

parser = LarkSeqFileParser().parser
contextual = parser.parser.lexer
table = parser.parser.parser._parse_table

# The order in which Lark tries the terminals: the first that matches wins.
terminals = [t.name for t in contextual.root_lexer.terminals]
assert all(lexer.terminals == [t for t in contextual.root_lexer.terminals if t in lexer.terminals]
           for lexer in contextual.lexers.values()), "state lexers do not follow the root order"
ignored = sorted(contextual.root_lexer.ignore_types)
nonterminals = sorted({r.origin.name for row in table.states.values() for (a, r) in row.values() if str(a) == "Reduce"})
symbols = terminals + ["$END"] + nonterminals
# Lark numbers the states differently from run to run: renumber them breadth first from the start state.
states = [table.start_states["input"]]
for s in states:
    for name in sorted(table.states[s], key=symbols.index):
        action, arg = table.states[s][name]
        if str(action) == "Shift" and arg not in states:
            states.append(arg)
assert len(states) == len(table.states)
state_id = {s: i for i, s in enumerate(states)}
rules = []
rows = []
for s in states:
    row = []
    for name in sorted(table.states[s], key=symbols.index):
        action, arg = table.states[s][name]
        if str(action) == "Shift":
            row.append((symbols.index(name), f"Shift({state_id[arg]})"))
        else:
            if arg not in rules:
                rules.append(arg)
            row.append((symbols.index(name), f"Reduce({rules.index(arg)})"))
    rows.append(sorted(row))

print(f"// Generated by tools/gen_tables.py from the grammar of the Python GDS with lark {lark.__version__}. Do not edit.")
print()
print("#[derive(Debug, Clone, Copy, PartialEq)]")
print("pub enum Action {\n    Shift(u8),\n    Reduce(u8),\n}")
print("use Action::{Reduce, Shift};")
print()
print("/// Terminals in the order the lexer tries them, then `$END`, then the nonterminals.")
print(f"pub const SYMBOLS: [&str; {len(symbols)}] = [")
for name in symbols:
    print(f'    "{name}",')
print("];")
print(f"pub const TERMINALS: usize = {len(terminals)};")
print(f"pub const END: u8 = {len(terminals)};")
print(f"pub const IGNORED: [u8; {len(ignored)}] = [{', '.join(str(symbols.index(n)) for n in ignored)}];")
print(f"pub const START: u8 = {state_id[table.start_states['input']]};")
print(f"pub const ACCEPT: u8 = {state_id[table.end_states['input']]};")
print()
print("/// Per rule: the symbol it produces and the number of symbols it consumes.")
print(f"pub const RULES: [(u8, u8); {len(rules)}] = [")
for r in rules:
    print(f"    ({symbols.index(r.origin.name)}, {len(r.expansion)}), // {r.origin.name}: {' '.join(x.name for x in r.expansion)}")
print("];")
print()
print("/// Per state: (symbol, action), sorted by symbol.")
print(f"pub const STATES: [&[(u8, Action)]; {len(rows)}] = [")
for row in rows:
    print("    &[" + ", ".join(f"({sym}, {act})" for sym, act in row) + "],")
print("];")
